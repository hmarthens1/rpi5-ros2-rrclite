#!/usr/bin/env python3
"""results_macros.tex and results_real.tex from ../data/run_summary.json and sim_explore.json,
so the numbers in the paper are the numbers in the logs."""
import json
import os
import time

HERE = os.path.dirname(os.path.abspath(__file__))
R = json.load(open(os.path.join(HERE, "..", "data", "run_summary.json")))
S = json.load(open(os.path.join(HERE, "..", "data", "sim_explore.json")))["final"]
X = R.get("extra", {})


def f(v, nd=1):
    return ("%%.%df" % nd) % v if isinstance(v, (int, float)) else "--"


done = R["frontiers_reached"] + R["frontiers_seen_on_the_way"]
with open(os.path.join(HERE, "results_macros.tex"), "w") as o:
    o.write("%% generated by make_results_tex.py\n")
    o.write("\\newcommand{\\todaydate}{%s}\n" % time.strftime("%B %-d, %Y"))
    o.write("\\newcommand{\\simcoverage}{%.0f\\,\\%%}\n" % (100 * S["coverage"]))
    o.write("\\newcommand{\\simfree}{%.0f\\,m$^2$}\n" % S["free_area_m2"])
    o.write("\\newcommand{\\simdistance}{%.1f\\,m}\n" % S["distance_m"])
    o.write("\\newcommand{\\simgoals}{%d}\n" % S["goals"])
    o.write("\\newcommand{\\simsearchms}{%.0f\\,ms}\n" % S["mean_search_ms"])
    o.write("\\newcommand{\\resultsabstract}{In an unattended run the robot mapped %s\\,m$^2$ of a home in %s\\,min, "
            "driving %s\\,m to %d frontier goals (%d failed) %s; the frontier search took %s\\,ms on the Pi and the whole "
            "stack used about 1.5 of the Pi's four cores.}\n"
            % (f(R["explored_m2_final"], 0), f(R["duration_min"], 0), f(R["path_length_m"], 0), R["goals_sent"],
               R["goals_failed"], X.get("abstract_end", "and returned to its start"), f(R["search_ms_mean"], 0)))

rows = [
    ("Duration (start to end)", "%s min" % f(R["duration_min"], 1)),
    ("Mapped area (known cells)", "%s m$^2$" % f(R["explored_m2_final"], 1)),
    ("Free / occupied area in the saved map", "%s / %s m$^2$" % (f(R["map_free_m2"], 1), f(R["map_occupied_m2"], 1))),
    ("Map extent", "%s $\\times$ %s m" % (f(R["map_size_m"][0], 1), f(R["map_size_m"][1], 1))),
    ("Path length (SLAM poses, 5\\,cm steps)", "%s m" % f(R["path_length_m"], 1)),
    ("Mean speed over the run", "%s m/s" % f(R["path_length_m"] / (60 * R["duration_min"]), 3)),
    ("Frontier goals sent", "%d" % R["goals_sent"]),
    ("\\quad reached", "%d" % R["frontiers_reached"]),
    ("\\quad seen on the way (cancelled)", "%d" % R["frontiers_seen_on_the_way"]),
    ("\\quad failed (blacklisted)", "%d" % R["goals_failed"]),
    ("Operator interventions", "%d" % R["operator_pauses"]),
    ("Frontier search on the Pi, mean / max", "%s / %s ms" % (f(R["search_ms_mean"], 0), f(R["search_ms_max"], 0))),
    ("Candidate frontiers per search, mean", "%s" % f(R["candidates_mean"], 1)),
    ("Mapping rate", "%s m$^2$/min" % f(R.get("area_rate_m2_per_min"), 1)),
    ("Battery, start / end", "%s / %s V" % (f(R["battery_v"][0], 2), f(R["battery_v"][1], 2)) if R.get("battery_v") else "--"),
    ("How it ended", R["end_reason"].replace("_", " ")),
]
with open(os.path.join(HERE, "results_real.tex"), "w") as o:
    o.write("%% generated by make_results_tex.py\n")
    o.write("\\subsection{Autonomous run in a home}\n")
    o.write(X.get("setup", "The robot was placed in a hallway of a furnished home, the exploration service was started "
                           "from the PC and Explore was pressed once."))
    o.write(" \\Cref{tab:run} summarises the run, \\cref{fig:runmap} shows the saved map with the path the robot "
            "chose and \\cref{fig:progress} the mapped area over time. Of the %d goals sent, %d were reached and %d were "
            "cancelled because the frontier behind them was seen on the way; %d failed (%s). " %
            (R["goals_sent"], R["frontiers_reached"], R["frontiers_seen_on_the_way"], R["goals_failed"],
             "; ".join(sorted(set(R["failures"]))) or "none"))
    o.write(X.get("discussion", ""))
    o.write("\n\n\\begin{table}[t]\n\\centering\\small\n\\caption{The autonomous run, from the explorer's log.}\\label{tab:run}\n")
    o.write("\\begin{tabular}{@{}lr@{}}\n\\toprule\n")
    for k, v in rows:
        o.write("%s & %s \\\\\n" % (k, v))
    o.write("\\bottomrule\n\\end{tabular}\n\\end{table}\n\n")
    o.write("\\begin{figure}[t]\n\\centering\n\\includegraphics[width=\\columnwidth]{figures/run_map.png}\n"
            "\\caption{Map saved at the end of the autonomous run (5\\,cm cells; white free, black occupied, grey "
            "unknown), with the robot's path from SLAM, its start and the frontier goals it chose.}\\label{fig:runmap}\n"
            "\\end{figure}\n\n")
    o.write("\\begin{figure}[t]\n\\centering\n\\includegraphics[width=\\columnwidth]{figures/run_progress.png}\n"
            "\\caption{Mapped area (blue) and open frontiers (red) during the run; grey lines mark goals sent.}"
            "\\label{fig:progress}\n\\end{figure}\n")
print("wrote results_macros.tex, results_real.tex")
